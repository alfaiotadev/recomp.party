export const KINDS = {
  recomp: "Static recompilation",
  port: "Source port",
  tool: "Recompiler / toolchain",
} as const;

const platform = z.enum(Object.keys(PLATFORMS) as [keyof typeof PLATFORMS, ...(keyof typeof PLATFORMS)[]]);
const repoSlug = z.string().regex(/^[\w.-]+\/[\w.-]+$/, "expected owner/name");

/** One curated entry in data/projects.yaml. Only a human merge puts it there. */
export const Project = z.strictObject({
  repo: repoSlug,
  game: z.string().min(1),
  platform,
  kind: z.enum(Object.keys(KINDS) as [keyof typeof KINDS, ...(keyof typeof KINDS)[]]),
  /** Recompiler or engine the project is built with, e.g. N64Recomp, XenonRecomp, ReXGlue. */
  tool: z.string().optional(),
  /** Credit for the work a port builds on (usually a decompilation), as owner/name or URL. */
  based_on: z.array(z.string()).optional(),
  /** Date the entry was added to recomp.party (YYYY-MM-DD). */
  added: z.iso.date(),
  note: z.string().optional(),
});
export type Project = z.infer<typeof Project>;

export const Projects = z.array(Project).superRefine((list, ctx) => {
  const seen = new Set<string>();
  for (const [i, p] of list.entries()) {
    const key = p.repo.toLowerCase();
    if (seen.has(key)) ctx.addIssue({ code: "custom", path: [i, "repo"], message: `duplicate repo ${p.repo}` });
    seen.add(key);
  }
});

export const OS = ["windows", "linux", "macos", "android", "ios", "web"] as const;

export const Release = z.object({
  tag: z.string(),
  name: z.string().nullable(),
  url: z.string(),
  publishedAt: z.string(),
  prerelease: z.boolean(),
  /** Operating systems guessed from the release asset file names. */
  os: z.array(z.enum(OS)),
  downloads: z.number(),
});
export type Release = z.infer<typeof Release>;

/** Generated by scripts/fetch.ts — never edit by hand. */
export const RepoSnapshot = z.object({
  repo: repoSlug,
  /** Canonical name if GitHub redirected (repo was renamed or moved). */
  canonical: repoSlug,
  description: z.string().nullable(),
  homepage: z.string().nullable(),
  stars: z.number(),
  license: z.string().nullable(),
  archived: z.boolean(),
  isFork: z.boolean(),
  pushedAt: z.string(),
  createdAt: z.string(),
  /** Newest releases first, at most a handful. */
  releases: z.array(Release),
  /** Publish dates of up to 100 newest releases, newest first — drives the timeline. */
  releaseDates: z.array(z.object({ date: z.string(), prerelease: z.boolean() })),
  releaseCount: z.number(),
});
export type RepoSnapshot = z.infer<typeof RepoSnapshot>;

export const Snapshot = z.object({
  generatedAt: z.string(),
  repos: z.record(z.string(), RepoSnapshot),
  /** Repos that could not be fetched in the last run (deleted, DMCA'd, private). */
  missing: z.array(z.string()),
});
export type Snapshot = z.infer<typeof Snapshot>;

/** data/rejected.yaml — repos discovery should not propose again (not a game project, opted out, …). */
export const Rejected = z.array(
  z.strictObject({
    repo: repoSlug,
    reason: z.string(),
    date: z.iso.date(),
  }),
);
export type Rejected = z.infer<typeof Rejected>;
